#!/bin/bash
# build-duckdb.sh ARCH — DuckDB with the MySQL, PostgreSQL and SQLite drivers built in, for
# one CPU (arm64 or x86_64): its static libraries, the drivers' libraries (MariaDB
# Connector/C, libpq, OpenSSL, curl, zlib, lz4), duckdb.h and their license files, in
# $SB_DUCKDB_WORK/out/ARCH. scripts/package-duckdb.sh combines both CPUs into the zip
# scripts/fetch-duckdb.sh installs.
#
# DuckDB's own prebuilt libraries leave the drivers out: the app downloaded them from
# extensions.duckdb.org at the first connection (~90 MB each), loaded unsigned. Built in,
# nothing is downloaded, and the App Store's rule against code downloaded at run time is
# met. Every input is pinned: DuckDB's tag, the drivers' commits (the ones DuckDB 1.5.6
# pins), vcpkg's tag (the one DuckDB's Makefile names), the GNU tools' checksums; the
# patches, vcpkg triplets and extension list are in vendor/DuckDB/recipe/.
#
# Needs Xcode's command-line tools, CMake and Ninja. About 40 minutes a CPU, the first
# time; the work folder keeps checkouts, vcpkg's binary cache and the build, so a rerun is
# quick. Builds outside the repo: an iCloud-synced folder (Desktop) breaks them.
set -euo pipefail
ARCH="${1:?usage: build-duckdb.sh arm64|x86_64}"
case "$ARCH" in
  arm64)  TRIPLET=arm64-osx ;;
  x86_64) TRIPLET=x64-osx ;;
  *) echo "usage: build-duckdb.sh arm64|x86_64"; exit 2 ;;
esac
cd "$(dirname "${BASH_SOURCE[0]}")/.."
RECIPE="$PWD/vendor/DuckDB/recipe"
WORK="${SB_DUCKDB_WORK:-$HOME/Library/Caches/SequelBridge-duckdb-build}"
mkdir -p "$WORK"
WORK="$(cd "$WORK" && pwd -P)"

DUCKDB_TAG=v1.5.6
MYSQL_COMMIT=99c2e091b153b7f1cbd449988332232e75684b41
POSTGRES_COMMIT=318dabb2474fc3789b0199301a2e661e19c1b4fc
SQLITE_COMMIT=5274128259f73166c1f37f01190a4601f84c5525
VCPKG_TAG=2025.12.12

step() { printf '\n==> %s\n' "$*"; }

# GNU m4, autoconf and automake, in the work folder: libpq's configure is generated by
# autoconf, and macOS's m4 (1.4.6) is too old for it. Nothing is installed system-wide.
gnu_tool() {   # path-in-gnu.org sha256
  local name; name=$(basename "$1")
  [ -f "$WORK/tools-src/$name.tar.gz" ] || curl -fsSL -o "$WORK/tools-src/$name.tar.gz" "https://ftp.gnu.org/gnu/$1.tar.gz"
  echo "$2  $WORK/tools-src/$name.tar.gz" | shasum -a 256 -c --quiet
  rm -rf "$WORK/tools-src/$name" && tar -xzf "$WORK/tools-src/$name.tar.gz" -C "$WORK/tools-src"
  (cd "$WORK/tools-src/$name" && PATH="$WORK/tools/bin:$PATH" ./configure -q --prefix="$WORK/tools" > /dev/null \
    && PATH="$WORK/tools/bin:$PATH" make -s -j"$(sysctl -n hw.ncpu)" > /dev/null 2>&1 && make -s install > /dev/null 2>&1)
}
if [ ! -x "$WORK/tools/bin/automake" ]; then
  step "GNU m4, autoconf, automake (for libpq)"
  mkdir -p "$WORK/tools-src"
  gnu_tool m4/m4-1.4.19 3be4a26d825ffdfda52a56fc43246456989a3630093cced3fbddf4771ee58a70
  gnu_tool autoconf/autoconf-2.72 afb181a76e1ee72832f6581c0eddf8df032b83e2e0239ef79ebedc4467d92d6e
  gnu_tool automake/automake-1.17 397767d4db3018dd4440825b60c64258b636eaf6bf99ac8b0897f06c89310acd
fi

# A checkout at a pinned commit, reset to it (so a patch applies to the same text every time).
checkout() {   # dir url ref [submodule]
  local dir="$WORK/$1"
  [ -d "$dir/.git" ] || git clone -q "$2" "$dir"
  git -C "$dir" fetch -q --tags origin
  git -C "$dir" -c advice.detachedHead=false checkout -q -f "$3"
  git -C "$dir" reset -q --hard
  if [ -n "${4:-}" ]; then git -C "$dir" submodule update -q --init "$4"; fi
}
step "checkouts"
checkout duckdb-mysql https://github.com/duckdb/duckdb-mysql "$MYSQL_COMMIT" database-connector
checkout duckdb-postgres https://github.com/duckdb/duckdb-postgres "$POSTGRES_COMMIT" database-connector
checkout duckdb-sqlite https://github.com/duckdb/duckdb-sqlite "$SQLITE_COMMIT" database-connector
git -C "$WORK/duckdb-mysql" apply "$RECIPE/patches/duckdb-mysql.patch"
git -C "$WORK/duckdb-postgres" apply "$RECIPE/patches/duckdb-postgres.patch"
# One DuckDB checkout per CPU: each keeps its build (build/release) for quick reruns.
[ -d "$WORK/duckdb-$ARCH/.git" ] || git -c advice.detachedHead=false clone -q --branch "$DUCKDB_TAG" --depth 1 https://github.com/duckdb/duckdb.git "$WORK/duckdb-$ARCH"
[ "$(git -C "$WORK/duckdb-$ARCH" describe --tags)" = "$DUCKDB_TAG" ] || { echo "duckdb-$ARCH isn't at $DUCKDB_TAG"; exit 1; }
if [ ! -x "$WORK/vcpkg/vcpkg" ]; then
  [ -d "$WORK/vcpkg/.git" ] || git clone -q https://github.com/microsoft/vcpkg.git "$WORK/vcpkg"
  git -C "$WORK/vcpkg" -c advice.detachedHead=false checkout -q "$VCPKG_TAG"
  "$WORK/vcpkg/bootstrap-vcpkg.sh" -disableMetrics > "$WORK/vcpkg-bootstrap.log" 2>&1
fi
sed "s#@WORK@#$WORK#g" "$RECIPE/extensions.cmake.in" > "$WORK/extensions.cmake"

step "DuckDB $DUCKDB_TAG with the drivers, $ARCH (log: $WORK/build-$ARCH.log)"
(
  cd "$WORK/duckdb-$ARCH"
  export PATH="$WORK/tools/bin:$PATH" VCPKG_TOOLCHAIN_PATH="$WORK/vcpkg/scripts/buildsystems/vcpkg.cmake" \
    VCPKG_OVERLAY_TRIPLETS="$RECIPE/triplets" MACOSX_DEPLOYMENT_TARGET=14.0 CMAKE_POLICY_VERSION_MINIMUM=3.5
  GEN=ninja USE_MERGED_VCPKG_MANIFEST=1 EXTENSION_CONFIGS="$WORK/extensions.cmake" OSX_BUILD_ARCH="$ARCH" \
    VCPKG_TARGET_TRIPLET="$TRIPLET" make gather-libs > "$WORK/build-$ARCH.log" 2>&1
) || { tail -30 "$WORK/build-$ARCH.log"; echo "the build failed: $WORK/build-$ARCH.log"; exit 1; }

step "out/$ARCH"
BUILD="$WORK/duckdb-$ARCH/build/release"
OUT="$WORK/out/$ARCH"
rm -rf "$OUT" && mkdir -p "$OUT/libs" "$OUT/include" "$OUT/licenses"
cp "$BUILD"/libs/*.a "$OUT/libs/"
for lib in mariadbclient pq pgcommon pgport ssl crypto curl z lz4; do
  cp "$BUILD/vcpkg_installed/$TRIPLET/lib/lib$lib.a" "$OUT/libs/"
done
cp "$WORK/duckdb-$ARCH/src/include/duckdb.h" "$OUT/include/"
for port in libmariadb libpq openssl curl zlib lz4; do
  cp "$BUILD/vcpkg_installed/$TRIPLET/share/$port/copyright" "$OUT/licenses/$port.txt"
done
cp "$WORK/duckdb-$ARCH/LICENSE" "$OUT/licenses/duckdb.txt"
for e in mysql postgres sqlite; do cp "$WORK/duckdb-$e/LICENSE" "$OUT/licenses/duckdb-$e.txt"; done
# The libraries DuckDB carries in its own source (fmt, RE2, Zstandard, Mbed TLS…): every
# one with a license file, whether or not this build compiles it in.
for d in "$WORK/duckdb-$ARCH"/third_party/*/; do
  f=$(ls "$d" | grep -i -E '^(LICENSE|COPYING)' | head -1 || true)
  if [ -n "$f" ]; then cp "$d$f" "$OUT/licenses/duckdb-third-party-$(basename "$d").txt"; fi
done
for lib in mysql_scanner_extension postgres_scanner_extension sqlite_scanner_extension; do
  [ -f "$OUT/libs/lib$lib.a" ] || { echo "lib$lib.a is missing: the driver wasn't built in"; exit 1; }
done
lipo -info "$OUT/libs/libduckdb_static.a"
ls "$OUT/libs" | wc -l | xargs echo "archives:"
